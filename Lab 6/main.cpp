// 1. Пузырьковая сортировка (Bubble Sort)
void bubbleSort(int arr[], int n) { // Функция принимает массив и его размер
    for (int i = 0; i < n - 1; i++) { // Внешний цикл: количество проходов
        bool swapped = false;       // Флаг: были ли обмены на текущем проходе
        for (int j = 0; j < n - i - 1; j++) { // Внутренний цикл: сравнение соседних элементов
            if (arr[j] > arr[j + 1]) { // Если текущий больше следующего
                swap(arr[j], arr[j + 1]); // Меняем их местами
                swapped = true;     // Отмечаем, что был обмен
            }                       
        }                           
        if (!swapped) break;        // Оптимизация: если обменов не было, массив отсортирован
    }                               
}                                  

// 2. Сортировка выбором (Selection Sort)
void selectionSort(int arr[], int n) { // Функция принимает массив и его размер
    for (int i = 0; i < n - 1; i++) { // Внешний цикл: проходим по массиву
        int minIndex = i;           // Предполагаем, что минимальный элемент - первый в неотсортированной части
        for (int j = i + 1; j < n; j++) { // Ищем минимальный элемент в оставшейся части
            if (arr[j] < arr[minIndex]) { // Если нашли элемент меньше
                minIndex = j;       // Запоминаем его индекс
            }                       
        }                           
        if (minIndex != i) {        // Если минимум не на текущем месте
            swap(arr[i], arr[minIndex]); // Меняем местами
        }                           
    }                               
}                                   

// Замер времени
long long measureTime(void (*sortFunc)(int[], int), int arr[], int n) { // Принимает указатель на функцию сортировки,массив и размер
    int* copy = new int[n];         // Выделяем память под копию массива
    for (int i = 0; i < n; i++) copy[i] = arr[i]; // Копируем исходный массив

    auto start = high_resolution_clock::now(); // Засекаем время начала
    sortFunc(copy, n);              // Вызываем переданную функцию сортировки
    auto end = high_resolution_clock::now();   // Засекаем время окончания

    delete[] copy;                  // Освобождаем память
    return duration_cast<microseconds>(end - start).count(); // Возвращаем время в микросекундах
}                                   

