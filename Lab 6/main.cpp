// Факториал числа (рекурсивно)
long long factorial(int n) {    // Функция принимает целое число n, возвращает long long (большие числа)
    if (n <= 1) return 1;       // Базовый случай: если n равно 0 или 1, факториал равен 1
    return n * factorial(n - 1); // Шаг рекурсии: n умножить на факториал предыдущего числа
}                               

// Числа Фибоначчи (рекурсивно)
int fibRecursive(int n) {       // Функция принимает номер числа Фибоначчи
    if (n <= 1) return n;       
    return fibRecursive(n - 1) + fibRecursive(n - 2); // Шаг рекурсии: сумма двух предыдущих
}                               

// Обход лабиринта 5x5 (рекурсивный поиск с возвратом)
const int N = 5;                // Константа, задающая размерность лабиринта (5x5)
char maze[N][N] = {             // Двумерный массив символов для представления лабиринта
    {'S', '.', '#', '.', '.'},  // S - старт, # - стена, . - пустая клетка
    {'.', '.', '#', '.', '#'},  // Строка 1
    {'.', '#', '.', '.', '.'},  // Строка 2
    {'.', '.', '.', '#', 'F'},  // Строка 3 
    {'#', '.', '.', '.', '.'}   // Строка 4
};                              
bool visited[N][N] = { false };   // Массив для отметки посещенных клеток 

bool findPath(int x, int y) {   // Функция поиска пути, принимает текущие координаты
    if (x < 0 || x >= N || y < 0 || y >= N) return false; // Проверка выхода за границы
    if (maze[x][y] == '#' || visited[x][y]) return false; // Проверка стены или уже посещенной клетки
    if (maze[x][y] == 'F') {    // Если достигли финиша
        maze[x][y] = '*';       // Отмечаем финиш звездочкой
        return true;            
    }                           

    visited[x][y] = true;       // Помечаем текущую клетку как посещенную
    maze[x][y] = '*';           // Отмечаем текущую клетку как часть пути

    // Рекурсивный поиск в 4 направлениях (вниз, вверх, вправо, влево)
    if (findPath(x + 1, y) || findPath(x - 1, y) || // Если путь найден внизу или вверху
        findPath(x, y + 1) || findPath(x, y - 1)) { // Или справа или слева
        return true;            // Возвращаем true, 
    }                           

    maze[x][y] = '.';           // Возврат (backtracking): если тупик, убираем звездочку
    return false;               // Возвращаем false для текущей ветки
}                              

//  Задача о ферзях (4x4)
bool isSafe(vector<int>& board, int row, int col) { // Проверка безопасности позиции
    for (int i = 0; i < row; i++) {                 // Проходим по всем предыдущим строкам
        if (board[i] == col || abs(board[i] - col) == abs(i - row)) { // Проверка столбца и диагоналей
            return false;       // Если ферзь бьет другого, позиция небезопасна
        }                      
    }                          
    return true;                
}                              

void solveQueens(int row, vector<int>& board, vector<vector<int>>& solutions) {
    if (row == 4) {             // Базовый случай: все 4 ферзя расставлены
        solutions.push_back(board); // Добавляем текущую расстановку в список решений
        return;                 
    }                          
    for (int col = 0; col < 4; col++) { // Пробуем поставить ферзя в каждый столбец
        if (isSafe(board, row, col)) {  // Если позиция безопасна
            board[row] = col;   // Ставим ферзя в эту строку и столбец
            solveQueens(row + 1, board, solutions); // Рекурсивно переходим к следующей строке
            board[row] = -1;    // убираем ферзя для других вариантов
        }                       
    }                           
}                              

